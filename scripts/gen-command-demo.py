#!/usr/bin/env python3
"""Build src/047-command-demo.mjs from demo-src/command-demo-fixtures.json + demo-src/command-demo.js."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
fix = json.loads((root / "demo-src/command-demo-fixtures.json").read_text())
rt = (root / "demo-src/command-demo.js").read_text()
js = "window.SF_DEMO_FIX=" + json.dumps(fix, separators=(",", ":")) + ";\n" + rt
out = """// v146 Command demo (generated by scripts/gen-command-demo.py; edit demo-src/ and re-run).
// /command-demo shows a made-up clinic's Command with sample data. All data lives in the browser; nothing is sent.
var COMMAND_DEMO_JS = %s;
async function commandDemoShell(request, env) {
  const i = await instGet(env, true).catch(() => null);
  if (i && i.custom) return new Response("Not found", { status: 404 });
  const res = appShell(request);
  if (res.status !== 200) return res;
  let html = await res.text();
  html = html.replace(/<title>[^<]*<\\/title>/, "<title>Harbour Command \\u00b7 live demo</title>").replace('<script src="/app/orb.js', '<script src="/app/demo.js?v=' + APP.v + '" defer></script><script src="/app/orb.js');
  const h = new Headers(res.headers); h.delete("ETag");
  return new Response(html, { status: 200, headers: h });
}
""" % json.dumps(js)
(root / "src/047-command-demo.mjs").write_text(out)
print("wrote", len(out))
